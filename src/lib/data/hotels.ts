export function getHotel(id: string): Hotel | undefined {
  return hotels.find((hotel) => hotel.id === id);
}

export function getFeaturedHotels(limit = 6): Hotel[] {
  return hotels.filter((hotel) => hotel.featured).slice(0, limit);
}

export function getSimilarHotels(hotel: Hotel, limit = 3): Hotel[] {
  return hotels
    .filter((candidate) => candidate.id !== hotel.id)
    .map((candidate) => ({
      candidate,
      score:
        candidate.tags.filter((tag) => hotel.tags.includes(tag)).length +
        (candidate.country === hotel.country ? 2 : 0),
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((entry) => entry.candidate);
}

export type HotelFilterState = {
  query?: string;
  maxPrice?: number;
  categories?: string[];
  minRating?: number;
  amenityTags?: string[];
};

/** Client-side search + filter + sort used by the results explorer. */
export function filterHotels(all: Hotel[], filters: HotelFilterState): Hotel[] {
  const query = filters.query?.trim().toLowerCase();

  return all.filter((hotel) => {
    if (query) {
      const haystack = [
        hotel.name,
        hotel.city,
        hotel.country,
        hotel.region,
        hotel.category,
        ...hotel.tags,
      ]
        .join(" ")
        .toLowerCase();
      if (!haystack.includes(query)) return false;
    }
    if (filters.maxPrice && hotel.pricePerNight > filters.maxPrice) return false;
    if (filters.minRating && hotel.rating < filters.minRating) return false;
    if (filters.categories?.length && !filters.categories.includes(hotel.category)) {
      return false;
    }
    if (filters.amenityTags?.length) {
      const every = filters.amenityTags.every((key) =>
        hotel.amenities.includes(key as Hotel["amenities"][number]),
      );
      if (!every) return false;
    }
    return true;
  });
}

export function sortHotels(list: Hotel[], sort: string): Hotel[] {
  const sorted = [...list];
  switch (sort) {
    case "price-asc":
      return sorted.sort((a, b) => a.pricePerNight - b.pricePerNight);
    case "price-desc":
      return sorted.sort((a, b) => b.pricePerNight - a.pricePerNight);
    case "rating":
      return sorted.sort((a, b) => b.rating - a.rating);
    case "reviews":
      return sorted.sort((a, b) => b.reviewCount - a.reviewCount);
    default:
      return sorted.sort(
        (a, b) => Number(Boolean(b.featured)) - Number(Boolean(a.featured)),
      );
  }
}
